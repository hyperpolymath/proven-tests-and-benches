# gen-matrix.sh — render taxonomy-coverage/COVERAGE-MATRIX.adoc from kit/ids.tsv and
# taxonomy-coverage/assets.tsv, and FAIL if any asset path is missing (a matrix row that
# points at nothing is a lie). Cells with no asset print "planned sN"; the sweep
# comes from the owner's order (26 Nov): s1 unit/smoke/build/P2P, s2 the rest of
# CRG C + aspects + benches, s3 property/fuzz/compat/lifecycle/mutation, s4 all.
# `gen-matrix.sh --check` regenerates to a temp file and diffs (CDF drift gate).
# Exit 0 ok; 1 missing path or drift; 2 inputs missing.
set -u
here="$(cd "$(dirname "$0")" && pwd)"; root="$(dirname "$here")"
ids="$root/kit/ids.tsv"; assets="$here/assets.tsv"; out="$here/COVERAGE-MATRIX.adoc"
[ -r "$ids" ] && [ -r "$assets" ] || { echo "NO CHECK PERFORMED: ids/assets missing" >&2; exit 2; }
[ "${1:-}" = "--check" ] && { dest="$(mktemp)"; check=1; } || { dest="$out"; check=0; }
langs="rust idris2 julia zig elixir gleam bash agda any"
sweep() { case "$1" in UT|SMK|BLD|P2P) echo 1;; PBT|FUZ|CMP|LCY|MUT) echo 3;; EXE|CHS) echo 4;; *) echo 2;; esac; }
bad=0
while IFS=$'\t' read -r id lang st path; do
  case "$id" in \#*|"") continue;; esac
  [ -e "$root/$path" ] || { echo "MISSING asset path: $id $lang -> $path" >&2; bad=1; }
done < "$assets"
{
cat <<'H'
// SPDX-License-Identifier: CC-BY-SA-4.0
// SPDX-FileCopyrightText: 2026 Jonathan D.A. Jewell (hyperpolymath) <jonathan.jewell@open.ac.uk>
// GENERATED by taxonomy-coverage/gen-matrix.sh from kit/ids.tsv + taxonomy-coverage/assets.tsv. Do not edit.
= Coverage matrix: TESTING-TAXONOMY against this repo's reusable assets
:toc:

For each of the 18 test categories, 14 aspects and 7 benchmark kinds, per language,
the reusable test or harness this repository ships, or the sweep in which it is planned.

Legend: *V* verified (run here; positive and negative controls pass), *U* written but
unverified (toolchain absent in the foundation container), *R*/*T* pre-existing
repo-local suite graded REAL / THIN in `TEST-NEEDS.adoc`, *sN* planned in sweep N, `-` none.
Language `any` is a Bash driver usable around any toolchain. A cell holding a
pre-existing REAL/THIN suite is repo-local evidence, not yet a parametrised reusable asset.
An empty cell is a gap, never a pass. The fail-closed consumer check is `kit/check-coverage.sh`.
H
for kind in category aspect bench; do
  echo; echo "== $(case $kind in category) echo Categories;; aspect) echo Aspects;; bench) echo Benchmark kinds;; esac)"; echo
  echo '[cols="1,2,'"$(echo $langs | wc -w)"'*1",options="header"]'; echo '|==='
  printf '| id | name'; for l in $langs; do printf ' | %s' "$l"; done; echo
  while IFS=$'\t' read -r k id name; do
    [ "$k" = "$kind" ] || continue
    printf '| %s | %s' "$id" "$name"
    for l in $langs; do
      cell=""
      while IFS=$'\t' read -r aid alang ast apath; do
        [ "$aid" = "$id" ] && [ "$alang" = "$l" ] || continue
        case "$ast" in verified) c="V";; unverified) c="U";; existing-REAL) c="R";; existing-THIN) c="T";; *) c="?";; esac
        case "$cell" in *"$c"*) ;; *) cell="${cell:+$cell/}$c";; esac
      done < <(grep -v '^#' "$assets")
      [ -n "$cell" ] || cell="s$(sweep "$id")"
      printf ' | %s' "$cell"
    done; echo
  done < <(grep -v '^#' "$ids")
  echo '|==='
done
echo; echo '== Asset paths'; echo; echo '[cols="1,1,1,4",options="header"]'; echo '|==='; echo '| id | language | status | path'
grep -v '^#' "$assets" | while IFS=$'\t' read -r a b c d; do echo "| $a | $b | $c | \`$d\`"; done
echo '|==='
} > "$dest"
if [ "$check" -eq 1 ]; then diff -q "$dest" "$out" >/dev/null 2>&1 || { echo "DRIFT: taxonomy-coverage/COVERAGE-MATRIX.adoc is stale; run taxonomy-coverage/gen-matrix.sh" >&2; rm -f "$dest"; exit 1; }; rm -f "$dest"; fi
[ "$bad" -eq 0 ]
